use thiserror::Error;

#[derive(Debug, Error)]
pub enum ParityError {
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
    #[error("yaml: {0}")]
    Yaml(#[from] serde_yaml::Error),
    #[error("schema: {0}")]
    Schema(String),
    #[error("duplicate: {0}")]
    Duplicate(String),
    #[error("missing: {0}")]
    Missing(String),
}
